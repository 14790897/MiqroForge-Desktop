/**
 * 欢迎页「起点任务」的两级子选项数据（issue #962）。
 *
 * 结构：MODE_SCENES[mode] -> 场景（L2）-> 任务（L3）。
 * 左栏渲染场景，右栏渲染该场景下的任务列表 + 选中任务的「场景方案」。
 * 点「用这个任务」时填进输入框的是 task.ask，不是 task.title。
 *
 * 目前是写死的常量；后续换成仓库上下文 / 历史任务 / 技能动态生成时，
 * 只需替换这个常量的来源，ChatConsole 的渲染逻辑不用动。
 */

export type WelcomeMode = 'fast' | 'daily' | 'code';

export interface StarterTask {
  /** 任务标题（右栏列表里显示的短句） */
  title: string;
  /** 任务图标（单个 emoji） */
  icon: string;
  /** 适用场景：什么情况下该用它 */
  scenario: string;
  /** 你会得到：产出物形态 */
  deliverable: string;
  /** 示例问法：点「用这个任务」后填入输入框的那句话 */
  ask: string;
  /** 需要你提供：用户必须补充的信息 */
  needs: string;
}

export interface StarterScene {
  /** 场景名（左栏） */
  title: string;
  /** 场景图标（单个 emoji） */
  icon: string;
  tasks: readonly StarterTask[];
}

